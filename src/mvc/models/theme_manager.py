class ThemeManager:
    @staticmethod
    def get_theme_choices() -> list[tuple[str, str]]:
        """Devuelve lista de tuplas (Label, theme_key) para usar en UI."""
        return [
            ("✦ Minimalista Moderno", "minimal"),
            ("🏛 Institucional", "institutional"),
            ("⚙️ Técnico Claro", "blueprint"),
            ("🔱 Ejecutivo Oscuro", "executive"),
            ("❄ Nórdico Limpio", "nordic"),
            ("♛ Clásico Elegante", "elegant"),
        ]
        
    @staticmethod
    def get_theme(theme_name: str) -> dict:
        return THEMES.get(theme_name, THEMES['minimal'])
        
    @staticmethod
    def generate_root_css(theme_name: str) -> str:
        theme = ThemeManager.get_theme(theme_name)
        css_lines = [":root {"]
        for key, value in theme.items():
            if key == 'name':
                continue
            css_lines.append(f"  --{key.replace('_', '-')}: {value};")
        css_lines.append("}")
        return "\n".join(css_lines)
